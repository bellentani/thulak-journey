import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { animations, art } from "../src/lib/art.js";
import { gameContent } from "../src/lib/content.js";
import { locales } from "../src/lib/locales.js";
import { storyModeLocales, storyModes } from "../src/lib/story-modes.js";

const outputUrl = new URL("../site/shared-data.js", import.meta.url);

export async function buildSiteData() {
  const payload = {
    art,
    animations,
    gameContent,
    locales,
    storyModes,
    storyModeLocales
  };

  const fileContents = [
    "// This file is generated by scripts/build-site-data.js.",
    "// Do not edit it by hand.",
    "",
    `export const siteData = ${JSON.stringify(payload, null, 2)};`,
    ""
  ].join("\n");

  await writeFile(outputUrl, fileContents, "utf8");
}

const isDirectRun = process.argv[1] === fileURLToPath(import.meta.url);

if (isDirectRun) {
  await buildSiteData();
  console.log("Wrote site/shared-data.js");
}
